// Release signing — see android/key.properties.example for setup. Falls
// back to debug signing (with a build-time warning) so `flutter run
// --release` still works for local testing without a keystore; a real
// Play Store upload needs this file with a real keystore.
val keystorePropertiesFile = rootProject.file("key.properties")
val hasKeystoreProperties = keystorePropertiesFile.exists()
val keystoreProperties = Properties()
if (hasKeystoreProperties) {
    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
} else {
    logger.warn(
        "WARNING: android/key.properties not found — release builds will be " +
            "signed with the debug key. See android/key.properties.example."
    )
}

